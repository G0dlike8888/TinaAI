# Label key for bilingual display names, driven by the current UI language.
_label_key = "label_bg" if st.session_state["lang"] == "bg" else "label_en"


def _scenario_display_name(option_id: str) -> str:
    """Display label for the scenario selectbox, in the current UI language.
    Options are stable language-neutral ids; 'Custom' passes through."""
    if option_id == "Custom":
        return "Custom"
    return demo_logic.SCENARIOS[option_id][_label_key]


def _gating_rule_display_name(option_id: str) -> str:
    """Display label for the gating test-rule selectbox, in the current UI
    language."""
    return demo_logic.GATING_TEST_RULES[option_id][_label_key]


# ------------------------------------------------------------------
# API KEY — resolved fresh each run, never cached in session state and
# never rendered. None disables the Analyze button entirely, so no client
# is ever constructed and no paid request can be attempted without a key.
# ------------------------------------------------------------------
_api_key = demo_logic.resolve_api_key(st.secrets)


def _reset_inputs_and_result() -> None:
    """on_click callback: clear both inputs and the stored result.

    Runs before the script reruns, which is the only safe point to write
    widget-keyed session state. Submits nothing and calls no API.
    """
    st.session_state["rule_text"] = ""
    st.session_state["note_text"] = ""
    st.session_state["last_result"] = None
    st.session_state["preset_confirm_pending"] = None
    st.session_state["reset_toast_pending"] = True


def _load_gating_preset() -> None:
    """on_click callback: load a gating-filter preset into the rule field.

    Reads the selection from the widget's own session state rather than
    from bound args - args are frozen at render time and can go stale if
    the selection changed in the same run. The note field is never
    touched. If the rule field already holds different text, the first
    click only arms a confirmation warning; a second click on the same
    preset performs the replacement. Runs before the rerun, the only
    safe point to write widget-keyed state.
    """
    preset_id = st.session_state.get("gating_rule_selector")
    if preset_id not in demo_logic.GATING_TEST_RULES:
        return
    preset_rule = demo_logic.GATING_TEST_RULES[preset_id]["rule"]
    current = st.session_state.get("rule_text", "")
    if current.strip() and current != preset_rule:
        # The confirmation is armed against the EXACT (preset, rule text)
        # pair. Editing the rule, switching presets, or loading a scenario
        # in between makes the pair stale, so the next click re-arms
        # instead of replacing - a confirmation granted for one text can
        # never destroy different text.
        pending = st.session_state.get("preset_confirm_pending")
        armed = (
            isinstance(pending, dict)
            and pending.get("preset") == preset_id
            and pending.get("rule") == current
        )
        if not armed:
            st.session_state["preset_confirm_pending"] = {
                "preset": preset_id,
                "rule": current,
            }
            return
    st.session_state["rule_text"] = preset_rule
    st.session_state["preset_confirm_pending"] = None
    st.session_state["preset_toast_pending"] = True


def _render_stored_result(stored: dict, T: dict) -> None:
    """Re-render the stored analysis outcome from session state.

    Chrome (labels, notices, warnings) stays OUTSIDE the bordered response
    containers, so it cannot be copied as part of the assistant answer by
    accident. A failed filter never shows the "filter applied" banner — the
    fallback warning names the failure instead, and the base response is
    what gets displayed.
    """
    if stored["kind"] == "error":
        st.error(T["err_" + stored["category"]])
    elif stored["kind"] == "gated":
        if stored["filter_failed"]:
            with st.expander(T["base_expander"], expanded=False):
                with st.container(border=True):
                    st.write(stored["base_text"])
            st.markdown(T["filtered_header"])
            st.warning(
                T["filter_fallback"].format(
                    reason=T["err_" + stored["filter_error_category"]]
                )
            )
            with st.container(border=True):
                st.write(stored["base_text"])
        else:
            st.info(T["gating_info"])
            with st.expander(T["base_expander"], expanded=False):
                with st.container(border=True):
                    st.write(stored["base_text"])
            st.markdown(T["filtered_header"])
            with st.container(border=True):
                st.write(stored["filtered_text"])
            st.caption(T["base_available_caption"])
    else:
        with st.container(border=True):
            st.write(stored["base_text"])


st.title("TinaAI – AI Transaction Investigation Note Assistant")
st.subheader(T["subheader"])

tab1, tab2 = st.tabs([T["tab1"], T["tab2"]])

with tab1:
    for key in ("rule_text", "note_text"):
        if key not in st.session_state:
            st.session_state[key] = ""
    if "last_result" not in st.session_state:
        # Holds the most recent analysis (or its error state) so it survives
        # reruns triggered by something other than the Analyze button —
        # language toggle, gating checkbox, scenario picker. See col_output.
        st.session_state["last_result"] = None
    if "pending_request" not in st.session_state:
        # Two-phase submit: a click stores a snapshot here and reruns; the
        # processing run renders the Analyze button disabled (guarding
        # duplicate submission), performs the request, stores the result and
        # reruns again. None = idle.
        st.session_state["pending_request"] = None

    if "preset_confirm_pending" not in st.session_state:
        st.session_state["preset_confirm_pending"] = None

    if st.session_state.pop("reset_toast_pending", False):
        st.toast(T["reset_toast"])
    if st.session_state.pop("preset_toast_pending", False):
        st.toast(T["gating_test_toast"])

    busy = st.session_state["pending_request"] is not None

    # Persistent synthetic-data warning, visible before any analysis —
    # includes the plain statement never to paste real case material.
    st.warning(T["synthetic_warning"] + "\n\n" + T["no_real_data"], icon="⚠️")

    col_input, col_output = st.columns(2)

    with col_input:
        with st.container(border=True):
            st.markdown(T["input_header"])
            scenario_ids = ["Custom"] + list(demo_logic.SCENARIOS.keys())
            selected_scenario = st.selectbox(
                T["scenario_label"],
                options=scenario_ids,
                index=0,
                format_func=_scenario_display_name,
                key="scenario_selector",
                help=T["scenario_help"],
            )
            if selected_scenario == "Custom":
                # Custom mode needs no load action: the two fields below ARE
                # the primary inputs. Selecting Custom never erases typed
                # text; the explicit clear button below does that.
                st.caption(T["custom_mode_caption"])
                _rule_label = T["custom_rule_label"]
                _note_label = T["custom_note_label"]
            else:
                if st.button(T["load_scenario_btn"], key="load_scenario_btn",
                             disabled=busy):
                    scenario = demo_logic.SCENARIOS[selected_scenario]
                    st.session_state["rule_text"] = scenario["rule"]
                    st.session_state["note_text"] = scenario["note"]
                    # A pending preset confirmation refers to text that no
                    # longer exists - drop it.
                    st.session_state["preset_confirm_pending"] = None
                    st.toast(
                        T["loaded_toast"].format(name=scenario[_label_key])
                    )
                _rule_label = T["rule_label"]
                _note_label = T["note_label"]

            # No `value=` here: the widget's `key` already binds it to
            # st.session_state["rule_text"]/["note_text"], which the scenario
            # loader above and the preset callback set directly. Passing both
            # `value=` and `key=` for the same session_state entry is what
            # produced the Streamlit "widget was created with a default
            # value but also had its value set via the Session State API"
            # warning; the key alone is enough to pick up the loaded text.
            rule_input = st.text_area(
                _rule_label,
                height=100,
                key="rule_text",
            )
            st.caption(
                T["chars_caption"].format(
                    length=len(rule_input), limit=demo_logic.MAX_RULE_CHARS
                )
            )
            note_input = st.text_area(
                _note_label,
                height=250,
                key="note_text",
            )
            st.caption(
                T["chars_caption"].format(
                    length=len(note_input), limit=demo_logic.MAX_NOTE_CHARS
                )
            )
            analyze_clicked = st.button(
                T["analyze_btn"],
                key="analyze_btn",
                type="primary",
                use_container_width=True,
                disabled=busy or _api_key is None,
            )
            st.button(
                T["reset_btn"],
                key="reset_btn",
                on_click=_reset_inputs_and_result,
                disabled=busy,
                help=T["reset_help"],
                use_container_width=True,
            )

            if selected_scenario == "Custom":
                # Optional presets live BELOW the primary inputs, collapsed,
                # so Custom mode reads as free-text-first. Loading uses an
                # on_click callback (state writes before the rerun) and a
                # two-click confirmation when it would replace typed text.
                with st.expander(T["preset_expander"], expanded=False):
                    st.caption(T["preset_caption"])
                    st.selectbox(
                        T["gating_rule_label"],
                        options=list(demo_logic.GATING_TEST_RULES.keys()),
                        index=0,
                        format_func=_gating_rule_display_name,
                        key="gating_rule_selector",
                    )
                    _pending = st.session_state["preset_confirm_pending"]
                    if isinstance(_pending, dict) and (
                        _pending.get("preset")
                        == st.session_state.get("gating_rule_selector")
                        and _pending.get("rule")
                        == st.session_state.get("rule_text", "")
                    ):
                        st.warning(T["preset_overwrite_warning"])
                    elif _pending is not None:
                        # Stale confirmation (rule edited, preset switched,
                        # or scenario round-trip): drop it silently so the
                        # warning never lies and a stale grant can never
                        # replace newer text.
                        st.session_state["preset_confirm_pending"] = None
                    st.button(
                        T["load_gating_rule_btn"],
                        key="load_gating_rule_btn",
                        on_click=_load_gating_preset,
                        disabled=busy,
                    )
                    st.caption(T["gating_test_caption"])

    with col_output:
        with st.container(border=True):
            st.markdown(T["output_header"])
            apply_gating = st.checkbox(
                T["gating_checkbox"],
                value=False,
                key="apply_gating",
                help=T["gating_help"],
                disabled=busy,
            )
            if _api_key is None:
                st.warning(T["missing_key_warning"], icon="🔑")

            if busy:
                # Processing run: the Analyze button above was rendered
                # disabled, so a duplicate submission cannot start. The
                # snapshot in pending_request is what gets analyzed. A widget
                # interaction during this run makes Streamlit abort the
                # script mid-request; the finally below then clears the
                # pending flag while leaving the previously stored result
                # untouched.
                req = st.session_state["pending_request"]
                result = None
                try:
                    client = demo_logic.create_client(_api_key)
                    if req["gated"]:
                        base_text = None
                        try:
                            with st.spinner(T["reading_spinner"]):
                                with st.expander(
                                    T["base_expander"], expanded=False
                                ):
                                    base_text = st.write_stream(
                                        demo_logic.stream_analysis(
                                            client,
                                            SYSTEM_PROMPT,
                                            req["rule"],
                                            req["note"],
                                        )
                                    )
                        except Exception as exc:
                            result = {
                                "kind": "error",
                                "category": demo_logic.classify_provider_error(exc),
                            }
                        if base_text:
                            try:
                                with st.spinner(T["filter_spinner"]):
                                    filtered_text = demo_logic.apply_gating_filter(
                                        client, base_text
                                    )
                                result = {
                                    "kind": "gated",
                                    "base_text": base_text,
                                    "filtered_text": filtered_text,
                                    "filter_failed": False,
                                    "filter_error_category": None,
                                }
                            except Exception as exc:
                                result = {
                                    "kind": "gated",
                                    "base_text": base_text,
                                    "filtered_text": None,
                                    "filter_failed": True,
                                    "filter_error_category": (
                                        demo_logic.classify_provider_error(exc)
                                    ),
                                }
                        elif result is None:
                            # Base call completed but yielded no text: store
                            # it exactly as the non-gated branch would rather
                            # than dropping the run silently. Nothing to
                            # filter.
                            result = {"kind": "base", "base_text": ""}
                    else:
                        try:
                            with st.spinner(T["reading_spinner"]):
                                base_text = st.write_stream(
                                    demo_logic.stream_analysis(
                                        client,
                                        SYSTEM_PROMPT,
                                        req["rule"],
                                        req["note"],
                                    )
                                )
                            result = {"kind": "base", "base_text": base_text}
                        except Exception as exc:
                            result = {
                                "kind": "error",
                                "category": demo_logic.classify_provider_error(exc),
                            }
                except Exception as exc:
                    # Anything outside the per-call handlers above (client
                    # construction, result assembly) still maps to a concise
                    # category — never a raw traceback in the UI.
                    result = {
                        "kind": "error",
                        "category": demo_logic.classify_provider_error(exc),
                    }
                finally:
                    # result stays None only when the run was aborted by a
                    # Streamlit control-flow exception (user interaction
                    # mid-request) — keep the previous result in that case.
                    if result is not None:
                        st.session_state["last_result"] = result
                    st.session_state["pending_request"] = None
                # Rerun to re-render from stored state with the Analyze
                # button re-enabled.
                st.rerun()

            elif analyze_clicked:
                errors = demo_logic.validate_inputs(rule_input, note_input)
                if any(e["code"] in ("missing_rule", "missing_note")
                       for e in errors):
                    st.warning(T["empty_warning"])
                for e in errors:
                    if e["code"] == "rule_too_long":
                        st.error(
                            T["rule_too_long_warning"].format(
                                length=f"{e['length']:,}",
                                limit=f"{e['limit']:,}",
                            )
                        )
                    elif e["code"] == "note_too_long":
                        st.error(
                            T["note_too_long_warning"].format(
                                length=f"{e['length']:,}",
                                limit=f"{e['limit']:,}",
                            )
                        )
                if not errors:
                    st.session_state["pending_request"] = {
                        "rule": rule_input,
                        "note": note_input,
                        "gated": apply_gating,
                    }
                    st.rerun()
                elif st.session_state["last_result"] is not None:
                    # Keep the last stored result visible under the
                    # validation message instead of blinking it out for one
                    # run and back in on the next unrelated rerun.
                    _render_stored_result(st.session_state["last_result"], T)

            elif st.session_state["last_result"] is not None:
                # No fresh click this run (rerun came from the language
                # toggle, the gating checkbox, or a scenario/rule picker
                # instead) — re-render the last analysis rather than letting
                # it disappear. Shown as-generated; toggling the gating
                # checkbox afterwards does not retroactively re-filter it.
                _render_stored_result(st.session_state["last_result"], T)

with tab2:
    st.markdown(T["methodology_md"])
    st.markdown(T["demo_vs_skill_md"])

    st.markdown(T["pretest_header"])
    m1, m2, m3 = st.columns(3)
    m1.metric(T["metric1_label"], "66.1%")
    m2.metric(T["metric2_label"], "70%")
    m3.metric(T["metric3_label"], T["metric3_value"])

    st.markdown(T["pretest_md"])

    st.warning(
        T["synthetic_warning"],
        icon="⚠️",
    )

    st.caption(T["footer_caption"])
